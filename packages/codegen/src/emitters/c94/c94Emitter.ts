/**
 * 9.4/9.5 共享的 C lowering。Registry 中用到的 197 个 C 符号已通过
 * registry-lvgl95-parity.test.ts 与 9.5.0 真实符号表对账。
 */
export function emitCForVersionFromIr(
  ir: IRProject,
  diagnostics: Diagnostic[],
  lvglVersion: CEmitterVersion,
  options?: EmitC94Options,
): CEmitResult {
  const target: CTarget = options?.target ?? 'esp-idf';
  const diags = [...diagnostics];
  const colorFormat = resolveTargetColorFormat(ir, lvglVersion, options?.colorFormat, diags);
  if (options?.buildTarget !== undefined && options.buildTarget.lvglVersion !== lvglVersion) {
    diags.push({
      severity: 'error',
      code: 'E_BUILD_TARGET_VERSION_MISMATCH',
      message: `BuildTarget.lvglVersion=${options.buildTarget.lvglVersion} 与 emitter ${lvglVersion} 不一致`,
    });
  }
  if (lvglVersion === '9.5.0' && options?.buildTarget !== undefined
    && options.displayProfileRef === undefined) {
    diags.push({
      severity: 'error',
      code: 'E_DISPLAY_PROFILE_REF_REQUIRED',
      message: 'BuildTarget 发布 manifest 必须锁定带 revision 的 DisplayProfile 引用',
    });
  }
  const callbacks = new Set<CName>();

  const screenFiles: GeneratedFile[] = [];
  for (const screen of ir.screens) {
    screenFiles.push({ path: `screens/${screen.name}.h`, content: screenH(screen) });
    screenFiles.push({
      path: `screens/${screen.name}.c`,
      content: screenC(ir, screen, diags, callbacks, lvglVersion === '9.4.0'),
    });
  }

  const cbList = [...callbacks].sort();
  const actions = actionsFiles(cbList);
  const styles = stylesFiles(ir);
  const subjects = subjectsFiles(ir);

  const buildFiles: GeneratedFile[] =
    target === 'esp-idf' ? [{ path: 'CMakeLists.txt', content: cmakeLists(ir) }]
    : target === 'cmake' ? [{ path: 'CMakeLists.txt', content: cmakeListsGeneric(ir) }]
    : [];

  const files: GeneratedFile[] = [
    ...buildFiles,
    // 9.4 入口保持历史文件集不变;9.5 发布链强制带可追溯 manifest。
    ...(lvglVersion === '9.5.0'
      ? [{
          path: 'build-manifest.json',
          content: buildManifest(ir, target, lvglVersion, cbList, colorFormat, options),
        }]
      : []),
    { path: 'REQUIREMENTS.txt', content: requirementsTxt(ir, lvglVersion) },
    { path: 'INTEGRATION.md', content: integrationMd(ir, lvglVersion) },
    { path: 'ui_conf.h', content: uiConfH(ir) },
    { path: 'objects.h', content: objectsH(ir) },
    { path: 'styles.h', content: styles.h },
    { path: 'styles.c', content: styles.c },
    { path: 'subjects.h', content: subjects.h },
    { path: 'subjects.c', content: subjects.c },
    ...(ir.images.length > 0 ? [{ path: 'images.h', content: imagesH(ir) }] : []),
    ...(ir.fonts.length > 0 ? [{ path: 'fonts.h', content: fontsH(ir) }] : []),
    { path: 'ui.h', content: uiH(ir) },
    { path: 'ui.c', content: uiC(ir) },
    ...screenFiles,
    { path: 'actions.h', content: actions.h },
    { path: 'actions_default.c', content: actions.def },
    { path: 'actions.c', content: actions.user, overwrite: false },
  ];

  return { files, diagnostics: diags };
}

export function emitC94FromIr(
  ir: IRProject,
  diagnostics: Diagnostic[],
  options?: EmitC94Options,
): CEmitResult {
  return emitCForVersionFromIr(ir, diagnostics, '9.4.0', options);
}

/** 契约入口:emitC94(project, options?);options 缺省 target='esp-idf'(向后兼容) */
export function emitC94(project: LvProject, options?: EmitC94Options): CEmitResult {
  const { ir, diagnostics } = normalizeProject(project);
  return emitC94FromIr(ir, diagnostics, options);
}
