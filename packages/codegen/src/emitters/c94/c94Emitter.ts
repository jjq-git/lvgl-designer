/**
 * 单属性 setter 输出,含五种特殊模板:
 * - $each(intList):逐元素一行(chart series values → set_next_value)
 * - $strarr(stringQuotedList):static const char * 数组 + 调用(buttonmatrix map)
 * - $idx/$ored(orFlags 空格分组):逐按钮位或调用(buttonmatrix ctrl_map)
 * - $ptarr/$n(pointList):static lv_point_precise_t 数组 + 调用(line points)
 * - $imgarr/$n(stringList of imageRef):static const void * 数组 + 调用(animimg srcs)
 * 另:空模板跳过(widget 级特殊形态处理,如 lottie src);
 * 无 $v 模板按展开结果去重(spinner/imagebutton 多属性合一 setter),bool false 不发。
 */
function emitPropSetter(
  spec: PropSpec,
  v: PropValue,
  w: CWriter,
  env: SetterEnv,
  localCounter: { n: number },
): void {
  const tpl = spec.c.setter;
  if (tpl === '') return;
  if (tpl.includes('$ptarr')) {
    const nums = (Array.isArray(v) ? v : []).map(Number);
    const pairs: string[] = [];
    for (let i = 0; i + 1 < nums.length; i += 2) pairs.push(`{${nums[i]}, ${nums[i + 1]}}`);
    const arr = `points_${++localCounter.n}`;
    w.push(`static const lv_point_precise_t ${arr}[] = {${pairs.join(', ')}};`);
    const t = tpl.replace('$ptarr', arr).replace('$n', String(pairs.length));
    w.push(`${expandSetter(t, '', spec, env)};`);
    return;
  }
  if (tpl.includes('$imgarr')) {
    const names = (Array.isArray(v) ? v : [v]).map(String).filter(Boolean);
    const arr = `srcs_${++localCounter.n}`;
    w.push(`static const void * ${arr}[] = {${names.map((s) => `&img_${s}`).join(', ')}};`);
    const t = tpl.replace('$imgarr', arr).replace('$n', String(names.length));
    w.push(`${expandSetter(t, '', spec, env)};`);
    return;
  }
  if (tpl.includes('$strarr')) {
    const items = (Array.isArray(v) ? v : [v])
      .map((s) => formatValueForC(s as PropValue, { type: 'string' }));
    const arr = `map_${++localCounter.n}`;
    w.push(`static const char * ${arr}[] = {${[...items, '""'].join(', ')}};`);
    w.push(`${expandSetter(tpl.replace('$strarr', arr), '', spec, env)};`);
    return;
  }
  if (tpl.includes('$idx') && tpl.includes('$ored')) {
    const groups = String(v).trim().split(/\s+/).filter(Boolean);
    groups.forEach((group, idx) => {
      const ored = group
        .split('|')
        .map((t) => formatEnumForC(t.trim(), spec.enum))
        .join(' | ');
      w.push(`${expandSetter(tpl.replace('$idx', String(idx)).replace('$ored', ored), '', spec, env)};`);
    });
    return;
  }
  if (tpl.includes('$each')) {
    const items = Array.isArray(v) ? v : String(v).trim().split(/\s+/).map(Number);
    for (const item of items) {
      w.push(`${expandSetter(tpl.replace('$each', String(item)), '', spec, env)};`);
    }
    return;
  }
  if (!tpl.includes('$v')) {
    // 无参/合一 setter:bool 开关 false 不发(如 msgbox close_button);
    // 相同展开只发一次(spinner anim_params、imagebutton 同 state 三段)
    if (spec.type === 'bool' && v === false) return;
    const line = `${expandSetter(tpl, '', spec, env)};`;
    if (env.emitted.has(line)) return;
    env.emitted.add(line);
    w.push(line);
    return;
  }
  w.push(`${expandSetter(tpl, cValue(v, spec), spec, env)};`);
}

/**
 * canvas / lottie 特殊形态(manifest notes):
 * - canvas:LV_DRAW_BUF_DEFINE_STATIC(ARGB8888)+ set_draw_buf + fill_bg
 *   (fill_color 缺省 #ffffff,与自研 parser 默认一致;该 prop 标记 handled)
 * - lottie:static uint8_t 渲染缓冲 + lv_lottie_set_buffer;
 *   src → lv_lottie_set_src_data(extern 数组,符号 lottie_<name>[]/_size,如 xxd -i 生成)
 * width/height 只认纯 px,非纯 px 告警并按 100 处理。
 */
function emitDrawBufWidget(
  node: IRNode,
  objExpr: string,
  w: CWriter,
  ctx: ScreenGenCtx,
  localCounter: { n: number },
  handled: Set<string>,
): void {
  const px = (key: 'width' | 'height'): number => {
    const raw = node.props[key];
    if (typeof raw === 'number' && Number.isFinite(raw)) return raw;
    if (raw !== undefined) {
      ctx.diags.push({
        severity: 'warning', code: 'W_NON_PX_BUF_SIZE',
        message: `${node.type}.${key} 仅支持纯 px,绘制缓冲按 100 处理:${JSON.stringify(raw)}`,
        nodeId: node.id,
      });
    }
    return 100;
  };
  const bw = px('width');
  const bh = px('height');

  if (node.type === 'canvas') {
    const buf = `canvas_buf_${++localCounter.n}`;
    w.push(`LV_DRAW_BUF_DEFINE_STATIC(${buf}, ${bw}, ${bh}, LV_COLOR_FORMAT_ARGB8888);`);
    w.push(`LV_DRAW_BUF_INIT_STATIC(${buf});`);
    w.push(`lv_canvas_set_draw_buf(${objExpr}, &${buf});`);
    const fill = node.props['fill_color'] ?? '#ffffff';
    w.push(`lv_canvas_fill_bg(${objExpr}, ${cValue(fill, { type: 'color' })}, LV_OPA_COVER);`);
    handled.add('fill_color');
    return;
  }

  /* lottie */
  const buf = `lottie_buf_${++localCounter.n}`;
  w.push(`static uint8_t ${buf}[${bw} * ${bh} * 4];   /* ARGB8888 渲染缓冲 */`);
  w.push(`lv_lottie_set_buffer(${objExpr}, ${bw}, ${bh}, ${buf});`);
  const src = node.props['src'];
  if (src !== undefined) {
    const name = String(isConstRef(src) ? src.$const : src);
    w.push(`/* TODO: 提供动画数据符号(如 xxd -i ${name}.json 生成,符号名改成下面两个) */`);
    w.push(`extern const uint8_t lottie_${name}[];`);
    w.push(`extern const size_t lottie_${name}_size;`);
    w.push(`lv_lottie_set_src_data(${objExpr}, lottie_${name}, lottie_${name}_size);`);
  }
  handled.add('src');
}

function emitNodeBody(
  node: IRNode,
  objExpr: string,
  parentExpr: string,
  w: CWriter,
  ctx: ScreenGenCtx,
  localCounter: { n: number },
  isRoot: boolean,
): void {
  const env: SetterEnv = {
    objExpr, parentExpr, node, screenName: ctx.screen.name, emitted: new Set(),
  };

  /* ---- name(宏守卫,评审 R8) */
  if (node.named) {
    w.push('#if LV_USE_OBJ_NAME');
    w.push(`lv_obj_set_name(${objExpr}, "${node.name}");`);
    w.push('#endif');
  }

  /* ---- 自研控件特殊形态(manifest notes):canvas / lottie 的静态绘制缓冲 */
  const handled = new Set<string>();
  if (node.type === 'canvas' || node.type === 'lottie') {
    emitDrawBufWidget(node, objExpr, w, ctx, localCounter, handled);
  }

  /* ---- props(objBase → 专有,registry 顺序;root 的 width/height 由 display 尺寸决定;
   *      createProps 已在 create 实参消费,不再 setter) */
  const specs = node.useObjBase ? [...OBJ_BASE.props, ...node.ownPropSpecs] : [...node.ownPropSpecs];
  for (const spec of specs) {
    if (isRoot && (spec.key === 'width' || spec.key === 'height')) continue;
    if (handled.has(spec.key)) continue;
    const v = node.props[spec.key];
    if (v === undefined) continue;
    emitPropSetter(spec, v, w, env, localCounter);
  }

  /* ---- animimage:有帧序列则自动起播(与自研 parser 同语义) */
  if (node.type === 'animimage' && node.props['srcs'] !== undefined) {
    w.push(`lv_animimg_start(${objExpr});`);
  }

  /* ---- flags / states */
  for (const [f, v] of node.flags) {
    w.push(`lv_obj_set_flag(${objExpr}, LV_OBJ_FLAG_${f.toUpperCase()}, ${v ? 'true' : 'false'});`);
  }
  for (const [s, v] of node.states) {
    w.push(`lv_obj_set_state(${objExpr}, LV_STATE_${s.toUpperCase()}, ${v ? 'true' : 'false'});`);
  }

  /* ---- inline styles */
  for (const g of node.inlineStyles) {
    const sel = cSelector(g.selector);
    for (const [k, v] of Object.entries(g.props)) {
      const sp = STYLE_PROPS[k];
      if (!sp) continue;
      w.push(`lv_obj_set_style_${sp.cSuffix}(${objExpr}, ${cValue(v, sp)}, ${sel});`);
    }
  }

  /* ---- 命名样式 */
  for (const u of node.styleUses) {
    w.push(`lv_obj_add_style(${objExpr}, &style_${u.styleName}, ${cSelector(u.selector)});`);
  }

  /* ---- 绑定 */
  for (const b of node.bindings) {
    if (b.kind === 'prop') {
      if (b.prop === 'checked') {
        w.push(`lv_obj_bind_checked(${objExpr}, &subject_${b.subject});`);
      } else if (b.prop === 'text') {
        const fmt = b.fmt !== undefined ? JSON.stringify(b.fmt) : 'NULL';
        w.push(`lv_label_bind_text(${objExpr}, &subject_${b.subject}, ${fmt});`);
      } else if (b.prop === 'src') {
        w.push(`lv_image_bind_src(${objExpr}, &subject_${b.subject});`);
      } else {
        const fn = PROP_BIND_FN[b.prop]?.[node.type];
        if (!fn) {
          ctx.diags.push({
            severity: 'warning', code: 'W_UNSUPPORTED_BINDING',
            message: `C 通道暂不支持 ${node.type}.bind_${b.prop},已跳过`, nodeId: node.id,
          });
          continue;
        }
        w.push(`${fn}(${objExpr}, &subject_${b.subject});`);
      }
    } else if (b.kind === 'flag') {
      w.push(`lv_obj_bind_flag_if_${b.op}(${objExpr}, &subject_${b.subject}, LV_OBJ_FLAG_${b.flag.toUpperCase()}, ${b.refValue});`);
    } else {
      w.push(`lv_obj_bind_state_if_${b.op}(${objExpr}, &subject_${b.subject}, LV_STATE_${b.state.toUpperCase()}, ${b.refValue});`);
    }
  }

  /* ---- 事件 */
  for (const e of node.events) emitEvent(e, objExpr, w, ctx, localCounter);

  /* ---- 子节点(ChildSpec 三形态:add/getter 得句柄,virtual 直调父) */
  // menu:首个 page 自动 lv_menu_set_page(与自研 parser 同语义,预览可见)
  let menuPagePending = node.type === 'menu';
  for (const child of node.children) {
    if (child.childKind === 'virtual') {
      // 无对象:属性是 "(行,列)=值" 式调用,$parent 即本节点
      const childEnv: SetterEnv = {
        objExpr: '', parentExpr: objExpr, node: child,
        screenName: ctx.screen.name, emitted: new Set(),
      };
      w.push('');
      for (const spec of child.ownPropSpecs) {
        const v = child.props[spec.key];
        if (v === undefined) continue;
        emitPropSetter(spec, v, w, childEnv, localCounter);
      }
      continue;
    }
    const isFirstMenuPage = menuPagePending && child.type === 'menu-page';
    if (isFirstMenuPage) menuPagePending = false;
    if (child.named) {
      // 命名节点独立 create 函数;调用点回填 objects 结构体
      w.push(`ui_${ctx.screen.name}.${child.name} = create_${child.name}(${objExpr});`);
      if (isFirstMenuPage) {
        w.push(`lv_menu_set_page(${objExpr}, ui_${ctx.screen.name}.${child.name});`);
      }
      continue;
    }
    // add/getter(或普通 widget):句柄类型缺省 lv_obj_t *
    const needsHandle = isFirstMenuPage || Object.keys(child.props).some(
      (k) => !child.createPropSpecs.some((cp) => cp.key === k),
    ) || child.flags.length > 0 || child.states.length > 0
      || child.inlineStyles.length > 0 || child.styleUses.length > 0
      || child.bindings.length > 0 || child.events.length > 0
      || child.children.length > 0 || child.cPatch?.post !== undefined;
    w.push('');
    if (!needsHandle) {
      w.push(`${expandCreate(child, objExpr)};`);       // 句柄无人用,免 -Wunused
      continue;
    }
    const local = `${child.type.replace(/-/g, '_')}_${++localCounter.n}`;
    w.push(`${child.cHandleType ?? 'lv_obj_t *'} ${local} = ${expandCreate(child, objExpr)};`);
    if (isFirstMenuPage) w.push(`lv_menu_set_page(${objExpr}, ${local});`);
    emitNodeBody(child, local, objExpr, w, ctx, localCounter, false);
  }

  /* ---- cPatch：仅 9.4 历史兼容通道可发；9.5 普通发布严禁透传任意 C */
  if (node.cPatch?.post) {
    if (ctx.allowLegacyCPatch) {
      w.push(`/* USER-PATCH ${node.id} BEGIN */`);
      for (const line of node.cPatch.post.replace(/\$obj/g, objExpr).split('\n')) w.push(line);
      w.push(`/* USER-PATCH ${node.id} END */`);
    } else {
      ctx.diags.push({
        severity: 'error',
        code: 'E_CPATCH_FORBIDDEN',
        message: 'LVGL 9.5 普通发布禁止 cPatch；请改为 typed property，或通过独立 trusted extension 审批链处理',
        nodeId: node.id,
      });
    }
  }
}

function emitEvent(
  e: IREvent,
  objExpr: string,
  w: CWriter,
  ctx: ScreenGenCtx,
  localCounter: { n: number },
): void {
  const trig = cTrigger(e.trigger);
  switch (e.kind) {
    case 'callback': {
      ctx.callbacks.add(e.callback);
      const ud = e.userData !== undefined ? JSON.stringify(e.userData) : 'NULL';
      w.push(`lv_obj_add_event_cb(${objExpr}, ${e.callback}, ${trig}, ${ud});`);
      break;
    }
    case 'subject_set': {
      let v: string;
      if (e.subjectType === 'int') v = String(parseInt(e.value, 10) || 0);
      else if (e.subjectType === 'float') v = `${Number(e.value) || 0}f`;
      else v = JSON.stringify(e.value);
      w.push(`lv_obj_add_subject_set_${e.subjectType}_event(${objExpr}, &subject_${e.subject}, ${trig}, ${v});`);
      break;
    }
    case 'subject_toggle':
      w.push(`lv_obj_add_subject_toggle_event(${objExpr}, &subject_${e.subject}, ${trig});`);
      break;
    case 'subject_increment': {
      const step = e.step ?? 1;
      if (e.min === undefined && e.max === undefined && e.rollover === undefined) {
        w.push(`lv_obj_add_subject_increment_event(${objExpr}, &subject_${e.subject}, ${trig}, ${step});`);
      } else {
        const dsc = `inc_${++localCounter.n}`;
        w.push(`lv_subject_increment_dsc_t * ${dsc} = lv_obj_add_subject_increment_event(${objExpr}, &subject_${e.subject}, ${trig}, ${step});`);
        if (e.min !== undefined) w.push(`lv_obj_set_subject_increment_event_min_value(${objExpr}, ${dsc}, ${e.min});`);
        if (e.max !== undefined) w.push(`lv_obj_set_subject_increment_event_max_value(${objExpr}, ${dsc}, ${e.max});`);
        if (e.rollover !== undefined) w.push(`lv_obj_set_subject_increment_event_rollover(${objExpr}, ${dsc}, ${e.rollover ? 'true' : 'false'});`);
      }
      break;
    }
    case 'screen_load':
    case 'screen_create': {
      // 目标屏可能尚未创建 → 生成惰性跳板(ui_<name>_create 可重入),等价 XML 的按名延迟解析
      const fnName = `screen_evt_${++ctx.trampolineN}_cb`;
      const tw = new CWriter();
      tw.push(`static void ${fnName}(lv_event_t * e)`);
      tw.push('{');
      tw.push(`    LV_UNUSED(e);`);
      tw.push(`    lv_screen_load_anim(ui_${e.screenName}_create(), ${cScreenAnim(e.animType)}, ${e.duration ?? 0}, ${e.delay ?? 0}, false);`);
      tw.push('}');
      ctx.trampolines.push(tw.toString());
      w.push(`lv_obj_add_event_cb(${objExpr}, ${fnName}, ${trig}, NULL);`);
      break;
    }
  }
}

/** 命名节点 create 函数定义(后序:子函数先于调用者) */
function emitNamedCreateFns(node: IRNode, w: CWriter, ctx: ScreenGenCtx): void {
  for (const c of node.children) emitNamedCreateFns(c, w, ctx);
  if (!node.named || node === ctx.screen.root) return;
  const counter = { n: 0 };
  w.push(`static lv_obj_t * create_${node.name}(lv_obj_t * parent)`);
  w.push('{');
  const bw = new CWriter();
  bw.push(`lv_obj_t * obj = ${expandCreate(node, 'parent')};`);
  emitNodeBody(node, 'obj', 'parent', bw, ctx, counter, false);
  bw.push('return obj;');
  for (const line of bw.toString().replace(/\n$/, '').split('\n')) {
    w.push(line === '' ? '' : `    ${line}`);
  }
  w.push('}');
  w.push('');
}

function collectNamed(node: IRNode, out: IRNode[]): void {
  if (node.named) out.push(node);
  for (const c of node.children) collectNamed(c, out);
}

function screenC(
  ir: IRProject,
  screen: IRScreen,
  diags: Diagnostic[],
  callbacks: Set<CName>,
  allowLegacyCPatch: boolean,
): string {
  const ctx: ScreenGenCtx = {
    ir, screen, diags, trampolines: [], trampolineN: 0, callbacks, allowLegacyCPatch,
  };
  const w = new CWriter();

  // 先生成树体(边走边收集 trampolines/callbacks),再拼文件
  const fnsW = new CWriter();
  emitNamedCreateFns(screen.root, fnsW, ctx);

  const rootCounter = { n: 0 };
  const bodyW = new CWriter();
  bodyW.push(`if(ui_${screen.name}.root) return ui_${screen.name}.root;`);
  bodyW.push('');
  bodyW.push('lv_obj_t * root = lv_obj_create(NULL);');
  bodyW.push(`ui_${screen.name}.root = root;`);
  bodyW.push(`lv_obj_set_width(root, ${ir.display.width});`);
  bodyW.push(`lv_obj_set_height(root, ${ir.display.height});`);
  emitNodeBody(screen.root, 'root', '', bodyW, ctx, rootCounter, true);
  bodyW.push('return root;');

  w.push(`/* screens/${screen.name}.c — ${GEN_HEADER.slice(3, -3).trim()} */`);
  w.push('#include "../ui.h"');
  w.push('');
  w.push(`ui_${screen.name}_t ui_${screen.name};`);
  w.push('');
  for (const t of ctx.trampolines) {
    for (const line of t.replace(/\n$/, '').split('\n')) w.push(line);
    w.push('');
  }
  const fnsText = fnsW.toString().replace(/\n+$/, '');
  if (fnsText.trim() !== '') {
    for (const line of fnsText.split('\n')) w.push(line);
    w.push('');
  }
  w.push(`lv_obj_t * ui_${screen.name}_create(void)`);
  w.push('{');
  for (const line of bodyW.toString().replace(/\n$/, '').split('\n')) {
    w.push(line === '' ? '' : `    ${line}`);
  }
  w.push('}');
  w.push('');
  w.push(`void ui_${screen.name}_destroy(void)`);
  w.push('{');
  w.push(`    if(!ui_${screen.name}.root) return;`);
  w.push(`    lv_obj_delete(ui_${screen.name}.root);`);
  w.push(`    lv_memzero(&ui_${screen.name}, sizeof(ui_${screen.name}));`);
  w.push('}');
  return w.toString();
}

