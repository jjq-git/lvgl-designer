const COLOR_FORMAT_DEPTH: Partial<Record<ColorFormat, 16 | 24 | 32>> = {
  RGB565: 16,
  RGB565_SWAPPED: 16,
  RGB888: 24,
  XRGB8888: 32,
  ARGB8888: 32,
};

function resolveTargetColorFormat(
  ir: IRProject,
  lvglVersion: CEmitterVersion,
  requested: ColorFormat | undefined,
  diagnostics: Diagnostic[],
): ColorFormat | null {
  if (lvglVersion === '9.4.0') return null;
  if (requested === undefined) {
    if (ir.display.colorDepth === 16) {
      diagnostics.push({
        severity: 'error',
        code: 'E_COLOR_FORMAT_CONFIRM_REQUIRED',
        message: 'v1 colorDepth=16 无法区分 RGB565 与 RGB565_SWAPPED，发布前必须由 DisplayProfile 明确确认',
      });
      return null;
    }
    return ir.display.colorDepth === 24 ? 'RGB888' : 'XRGB8888';
  }
  if (COLOR_FORMAT_DEPTH[requested] !== ir.display.colorDepth) {
    diagnostics.push({
      severity: 'error',
      code: 'E_COLOR_FORMAT_DEPTH_MISMATCH',
      message: `DisplayProfile.colorFormat=${requested} 与 v1 colorDepth=${ir.display.colorDepth} 不兼容`,
    });
    return null;
  }
  return requested;
}

