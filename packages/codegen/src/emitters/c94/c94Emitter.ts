/** 资产引用的 C 符号约定:图片 img_<name>、自定义字体 font_<name>、内置 lv_font_montserrat_N */
function cAssetRef(value: PropValue, type: 'imageRef' | 'fontRef'): string {
  if (isConstRef(value)) return constMacroName(value.$const);
  const name = String(value);
  if (type === 'fontRef') {
    return M1_TEXT_FONTS.includes(name) ? `&lv_font_${name}` : `&font_${name}`;
  }
  return `&img_${name}`;
}

function cValue(
  value: PropValue,
  spec: { type: PropSpec['type'] | 'gradRef'; enum?: PropSpec['enum'] },
): string {
  if (spec.type === 'imageRef' || spec.type === 'fontRef') {
    return cAssetRef(value, spec.type);
  }
  if (spec.type === 'gradRef') return `&grad_${String(value)}`;   // 渐变二期,占位约定
  if (spec.type === 'subject') return `&subject_${String(value)}`;
  if (spec.type === 'styleRef') return `&style_${String(value)}`;
  if (spec.type === 'orFlags') {
    // 'a|b' → PREFIX_A | PREFIX_B(单组;buttonmatrix ctrl_map 的多组走 $idx/$ored)
    return String(value)
      .split('|')
      .map((t) => formatEnumForC(t.trim(), spec.enum))
      .join(' | ');
  }
  return formatValueForC(value, { type: spec.type, enum: spec.enum });
}

/** LV_PART_* | LV_STATE_*;空 selector → 0(part 在前,design/01 §4.3) */
function cSelector(sel: Selector | undefined): string {
  const parts: string[] = [];
  if (sel?.part && sel.part !== 'main') parts.push(`LV_PART_${sel.part.toUpperCase()}`);
  for (const s of sel?.states ?? []) {
    if (s !== 'default') parts.push(`LV_STATE_${s.toUpperCase()}`);
  }
  return parts.length > 0 ? parts.join(' | ') : '0';
}

function cTrigger(trigger: string): string {
  return `LV_EVENT_${trigger.toUpperCase()}`;
}

function cScreenAnim(anim: string | undefined): string {
  return `LV_SCREEN_LOAD_ANIM_${(anim ?? 'none').toUpperCase()}`;
}

interface SetterEnv {
  objExpr: string;                  // $obj:本节点句柄(virtual 子元素无)
  parentExpr: string;               // $parent:父 widget 句柄(chart/table/spangroup 等)
  node: IRNode;
  screenName: string;               // $ref:同 screen 命名 widget → ui_<screen>.<name>
  emitted: Set<string>;             // 无 $v 模板的去重域(spinner 合一 setter / imagebutton 按 state 聚合)
}

/**
 * setter 模板展开:
 * $obj / $parent / $v / $ref(widget 名引用)
 * $<createProp>(构造实参,如 $row/$column/$axis)
 * $<companion>:<T>:<F>(bool 三目)/ $<companion>(枚举取 token;string 引号化,缺省 NULL)
 */
function expandSetter(
  template: string,
  valueExpr: string,
  spec: PropSpec,
  env: SetterEnv,
): string {
  const { node } = env;
  return template.replace(
    /\$([a-z_][a-z0-9_]*)(?::([A-Za-z_0-9]+):([A-Za-z_0-9]+))?/g,
    (_m, name: string, t?: string, f?: string) => {
      if (name === 'obj') return env.objExpr;
      if (name === 'parent') return env.parentExpr;
      if (name === 'v') return valueExpr;
      if (name === 'ref') return `ui_${env.screenName}.${String(node.props[spec.key])}`;
      if (t !== undefined && f !== undefined) {
        return node.props[name] === true ? t : f;
      }
      const createSpec = node.createPropSpecs.find((c) => c.key === name);
      if (createSpec) {
        const v = node.props[name] ?? createSpec.default;
        return v === undefined ? '0' : cValue(v, createSpec);
      }
      const comp = spec.companions?.find((c) => c.key === name);
      if (comp?.enum) {
        const token = String(node.props[name] ?? comp.enum.tokens[0]);
        return formatEnumForC(token, comp.enum);
      }
      if (comp?.type === 'string') {
        const v = node.props[name];
        return v === undefined ? 'NULL' : formatValueForC(v, { type: 'string' });
      }
      // 兄弟专有属性(spinner 合一 setter 的 $anim_duration/$angle、
      // imagebutton 按 state 聚合的 $src_*):值缺省取 registry default;
      // 无 default 的指针类(imageRef/string)发 NULL
      const sibling = node.ownPropSpecs.find((p) => p.key === name);
      if (sibling) {
        const v = node.props[name] ?? sibling.default;
        if (v === undefined) {
          return sibling.type === 'imageRef' || sibling.type === 'string' ? 'NULL' : '0';
        }
        return cValue(v, sibling);
      }
      return String(node.props[name] ?? '0');
    },
  );
}

/**
 * cCreate 模板展开:$parent + $<createProp>(实参来自 createProps,缺省取 default)。
 * 'lv_chart_add_series($parent, $color, $axis)' →
 * 'lv_chart_add_series(obj, lv_color_hex(0xff0000), LV_CHART_AXIS_PRIMARY_Y)'
 */
function expandCreate(node: IRNode, parentExpr: string): string {
  return node.cCreate.replace(/\$([a-z_][a-z0-9_]*)/g, (m, name: string) => {
    if (name === 'parent') return parentExpr;
    const cp = node.createPropSpecs.find((c) => c.key === name);
    if (cp) {
      const v = node.props[cp.key] ?? cp.default;
      if (v === undefined) {
        // optional 指针实参(menu-page title / list-button·win-button icon)缺省 NULL
        return cp.type === 'string' || cp.type === 'imageRef' ? 'NULL' : '0';
      }
      return cValue(v, cp);
    }
    return m;
  });
}

/* ------------------------------------------------------------------ consts */

function constDefine(c: ConstDef): string {
  let v: string;
  switch (c.type) {
    case 'color': v = `lv_color_hex(0x${c.value.replace(/^#/, '').replace(/^0x/i, '')})`; break;
    case 'string': v = JSON.stringify(c.value); break;
    case 'percent': v = `lv_pct(${c.value.replace(/%$/, '')})`; break;
    default: v = c.value;                    // int / px
  }
  return `#define ${constMacroName(c.name)} ${v}`;
}

/* ----------------------------------------------------------------- writer */

class CWriter {
  private lines: string[] = [];
  private depth = 0;
  push(text = ''): void {
    this.lines.push(text === '' ? '' : `${'    '.repeat(this.depth)}${text}`);
  }
  open(text: string): void { this.push(text); this.push('{'); this.depth++; }
  close(): void { this.depth--; this.push('}'); }
  toString(): string { return `${this.lines.join('\n')}\n`; }
}

